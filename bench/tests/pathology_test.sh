#!/usr/bin/env bash
# FastSuite pathology corpus — integration test.
#
# Five adversarial fixtures, one per defect the Phase D campaign found only by
# measuring real sequencing data (zero of the five were caught by the 461-test
# unit suite, because the suite tests the code as written, not the inputs that
# break it). Each test below runs a RELEASE binary against a committed fixture
# and asserts the post-fix behaviour: if any defect is reintroduced, the
# corresponding assertion fails here.
#
# Usage: bash bench/tests/pathology_test.sh
# Exits 0 only if every fixture reproduces/guards its defect. Fixtures are
# generated by bench/fixtures/make_fixtures.py and committed to bench/fixtures/.
set -uo pipefail

cd "$(dirname "$0")/../.."   # repo root

FIX=bench/fixtures
FC=tools/fastcheck/target/release/fastcheck
FS=tools/fastsim/target/release/fastsim
SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT

pass=0
fail=0
ok()   { printf "  \033[32mPASS\033[0m %s\n" "$1"; pass=$((pass+1)); }
bad()  { printf "  \033[31mFAIL\033[0m %s\n" "$1"; fail=$((fail+1)); }

# assert_le NAME ACTUAL BOUND — actual must be <= bound. Args: $1 name, $2 actual, $3 bound.
assert_le() { if awk "BEGIN{exit !($2 <= $3)}"; then ok "$1 ($2 <= $3)"; else bad "$1 (got $2, want <= $3)"; fi; }
assert_ge() { if awk "BEGIN{exit !($2 >= $3)}"; then ok "$1 ($2 >= $3)"; else bad "$1 (got $2, want >= $3)"; fi; }
assert_eq() { if [ "$2" = "$3" ]; then ok "$1 ($2)"; else bad "$1 (got $2, want $3)"; fi; }

# json_get FILE KEY — pull a scalar out of the report JSON
json_get() { python3 -c "import json,sys;print(json.load(open('$1'))['metrics']['$2'])"; }

echo "Building release binaries..."
for t in fastcheck fastsim; do
    (cd "tools/$t" && cargo build --release --offline >/dev/null 2>&1) || { echo "  build failed: $t"; exit 2; }
done

echo
echo "Defect 1 — fastsim 3' boundary rule (tail = {0}, last base must stay G)"
# Pre-fix: guard `t < read_len` fired at t == 0 and forced every read's LAST base
# non-G, collapsing the last-position G fraction to ~0.42% against a real ~23.5%.
# Post-fix: the rule is guarded by `t > 0`, so a no-tail-artefact, GC-rich genome
# keeps its natural last-base G (~25%).
if $FS --pairs 4000 --profile "$FIX/notail_profile.json" --out "$SCRATCH/sim" \
        --seed 42 -f --no-gzip --insert-min 80 --insert-mean 200 --insert-sd 40 \
        --drop-rate 0 >/dev/null 2>&1; then
    frac=$(python3 - "$SCRATCH" <<'PY'
import sys
s=sys.argv[1]; L=80; g=0; t=0
for fn in (s+"/sim_R1.fastq", s+"/sim_R2.fastq"):
    for i,line in enumerate(open(fn, encoding="ascii")):
        if i % 4 == 1:
            t+=1
            if line.rstrip("\n")[-1:] == "G": g+=1
print("%.4f" % (g/t) if t else "0.0")
PY
)
    # Biology gives ~0.35 G at the last base; a floor of 0.15 catches the pinned-to-0
    # regression while tolerating simulation noise. (Measured post-fix: 0.2434.)
    assert_ge "last-base G fraction stays natural (no 3' clamp)" "$frac" 0.15
else
    bad "fastsim run on notail profile"
fi

echo
echo "Defect 2 — fastcheck profile dup_rate == report duplication_level (merged R1+R2)"
# Pre-fix: profile dup_rate used accs.first() (R1 only); the report uses the merged
# fingerprint table. With mates that differ in duplicate rate the two disagreed by
# construction. Post-fix: both are the merged rate and must be equal.
if $FC "$FIX/paired_dup_R1.fastq" "$FIX/paired_dup_R2.fastq" \
        --json "$SCRATCH/rep.json" --profile "$SCRATCH/prof.json" >/dev/null 2>&1; then
    rep=$(json_get "$SCRATCH/rep.json" duplication_level)
    prof=$(python3 -c "import json;print(json.load(open('$SCRATCH/prof.json'))['dup_rate'])")
    if awk "BEGIN{exit !(($rep - $prof < 1e-4) && ($prof - $rep < 1e-4))}"; then
        ok "profile dup_rate ($prof) == report duplication_level ($rep)"
    else
        bad "profile dup_rate ($prof) != report duplication_level ($rep)"
    fi
    # And the merged rate must be the HIGH one (R2-driven), not the ~0 first-mate
    # reading: this is the half that catches a regression to accs.first(). R2
    # repeats one sequence 300x, so the merged level sits ~0.25 while an R1-only
    # profile would be ~0.0. A floor of 0.20 separates the two.
    assert_ge "merged rate reflects R2's duplicates, not R1's ~0" "$rep" 0.20
else
    bad "fastcheck paired run"
fi

echo
echo "Defect 3 — k-mer saturation completes fast (amortized eviction, no per-insert scan)"
# This fixture saturates the 1M-cap 12-mer space (8000 x 150 bp -> ~1.076M distinct
# 12-mers). NOTE: the pre-fix 40-minute pathology is NOT reproducible by any small
# synthetic stream (verified: even a faithful 1M-distinct/2M-insert stream finishes
# in <0.2s with the every-insert eviction) — the hang depends on the real DRR509062
# key distribution. This is a guard on the amortized eviction, not a hang repro.
t0=$SECONDS
if timeout 120 $FC "$FIX/kmer_saturation.fastq" --json "$SCRATCH/ksat.json" >/dev/null 2>&1; then
    dt=$((SECONDS - t0))
    assert_le "saturating scan finishes in a generous bound" "$dt" 30
    if [ -s "$SCRATCH/ksat.json" ]; then
        ok "k-mer spectrum emitted (output present)"
    else
        bad "no k-mer spectrum output"
    fi
else
    bad "fastcheck run on kmer_saturation fixture (timeout or error)"
fi

echo
echo "Defect 4 — Phred+64 bytes must not be silently decoded as +33"
# Pre-fix behaviour being guarded: a +64 file (bytes 66-105) is arithmetically
# ambiguous with +33 (min byte >= 64 proves neither). fastcheck must DECLARE that
# ambiguity on auto (certain == 0), and when the offset is forced to 64 the mean Q
# must land in the plausible 20-40 band rather than the impossible ~52 that a +33
# decode produces.
if $FC "$FIX/phred64.fastq" --json "$SCRATCH/q_auto.json" >/dev/null 2>&1 \
   && $FC "$FIX/phred64.fastq" --phred-offset 64 --json "$SCRATCH/q64.json" >/dev/null 2>&1; then
    certain=$(json_get "$SCRATCH/q_auto.json" phred_offset_certain)
    assert_eq "auto mode declares the +33/+64 ambiguity (certain == 0)" "$certain" "0"
    meanq=$(json_get "$SCRATCH/q64.json" mean_read_mean_q)
    if awk "BEGIN{exit !($meanq >= 15 && $meanq <= 45)}"; then
        ok "forced +64 mean Q is plausible ($meanq in [15,45])"
    else
        bad "forced +64 mean Q implausible ($meanq, expected ~20-40; ~52 = decoded as +33)"
    fi
else
    bad "fastcheck phred64 runs"
fi

echo
echo "Defect 5 — N-heavy padding counted as duplicates"
# Real libraries carry N-runs that are the MOST duplicated sequences, while the
# simulator emits no Ns. This fixture repeats one 80 bp N-run 400x among 600 unique
# reads. The fingerprint must count the N-runs as duplicates: duplication_level
# reflects them and the most-repeated sequence is the N-run. A regression that
# filtered non-ACGT sequences out of the fingerprint drops this to ~0.
if $FC "$FIX/nruns.fastq" --json "$SCRATCH/nrep.json" >/dev/null 2>&1; then
    dup=$(json_get "$SCRATCH/nrep.json" duplication_level)
    assert_ge "duplication_level reflects the repeated N-runs" "$dup" 0.30
    top=$(python3 - "$SCRATCH/nrep.json" <<'PY'
import json,sys
top=json.load(open(sys.argv[1]))["repeated_sequences"]["top"]
print(top[0]["count"] if top else 0)
PY
)
    assert_ge "top repeated sequence is the N-run (count >= 400)" "$top" 400
else
    bad "fastcheck nruns run"
fi

echo
printf "pathology corpus: %d passed, %d failed\n" "$pass" "$fail"
[ "$fail" -eq 0 ]
