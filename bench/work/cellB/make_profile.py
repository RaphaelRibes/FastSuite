#!/usr/bin/env python3
"""Cell B -- the synthetic PE-overlap value-test cohort.

WHY THIS EXISTS
---------------
`docs/plans/2026-10-19_004500-pe-overlap-with-without.md` needs two cells. Cell A
is the real corpus, used as a *spurious-fire guard*: it carries adapter
readthrough in only 11,395 of 10.2M pairs (0.11%), so it cannot measure value.
Cell B is the *value test* -- a cohort where the `--pe-overlap` mode has
something to find.

WHY A PLAIN READTHROUGH COHORT IS NOT ENOUGH (the confound this file avoids)
----------------------------------------------------------------------------
`bench/scripts/trim_report.py` classifies every mate by comparing the tool's
trim positions against the GROUND TRUTH's G-run lengths:

    if abs(t5-h) <= tol and abs(t3-t) <= tol:  'exact'
    elif t5 > h or t3 > t:                    'overtrim'

An ADAPTER trim is not a G-run. On a cohort whose GT has NO G-runs, every
adapter trim the tool makes is labelled 'overtrim' -- a false verdict. That is
exactly what Cell A measured (8,533 of 11,299 readthrough pairs labelled
overtrim) and it is why Cell A cannot be read.

This profile therefore carries BOTH halves:

  (a) real G-runs -- 3' polyG tails and 5' leading G-runs -- so the G-run
      boundary stays a meaningful exact/overtrim reference for the polyX scan,
      and
  (b) adapter readthrough -- a fixed 15% of pairs have an insert below the read
      length, so the PE mode has a boundary to find. The readthrough is the
      REAL Illumina TruSeq R1 adapter (AGATCGGAAGAGCACACGTCTGAACTCCAGTCA), the
      same sequence fastprep's built-in catalogue carries, so the mode's
      "readthrough past the boundary really is adapter" guard has something to
      match.

INSERT DISTRIBUTION
-------------------
Three components, in the profile builder's own convention (a saturating bin for
lengths past the measurement ceiling of 2L-12):

    component      share   range        role
    overlap        50%     150..288     mates overlap; no readthrough
    short          15%     112..149     readthrough 1..38 -> the PE mode's target
    saturated      35%     301          the fitter's saturating bin: no overlap,
                                          no readthrough, one bin is as faithful
                                          as a fitted tail

fastsim's insert CDF is built from a `{length: count}` histogram
(`Profile::sample_insert`), so the shares above are realised as a sparse
histogram with an explicit `0` bin at 0 (fastsim's `Cdf::from_map` expands it to
a dense vec over [0, max_len]; the zero bins cost nothing).

WHAT IS NOT MODELED, ON PURPOSE
-------------------------------
  * no N model (`n_run` absent) -- the report's recoverable/irreducible split
    needs a clean G-run class; N-runs are forced into 'irreducible' by
    construction and would only blur the readout.
  * no full-length spike (`full_length_rate: 0.0`) -- an all-G read is a drop
    class, not a trim class, and would add a large 'dropped' bucket with no
    bearing on the PE question.
  * `qual_noise` left at its default (0.0) so the emitted qualities are the
    profile's own integers.
  * `dup_rate: 0.0` -- a duplicate replays a stored pair verbatim, which would
    put byte-identical pairs in the cohort and distort the exact-rate
    denominators.

DETERMINISM
-----------
The cohort is regenerated byte-identically by:

    fastsim --pairs 400000 --profile <this>/cellB-profile.json \
             --out <this>/cohort/cellB --seed 4242 --force

`--seed 4242` is fixed here, so the GT, the FASTQs and every downstream number
are reproducible. See README.md in this directory.
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

READ_LEN = 150
ANCHOR = 12                       # fastprep's pe_overlap::ANCHOR
CEILING = 2 * READ_LEN - ANCHOR   # 288: the insert window's upper edge
SHORT_LO = 112                    # readthrough = READ_LEN - I in [1, 38]
SHORT_HI = READ_LEN - 1           # 149
SATURATING = 2 * READ_LEN + 1     # 301: the fitter's saturating bin

# --- weights ---------------------------------------------------------------
# The three insert components, in the profile builder's own units (a histogram
# is a weight vector; fastsim normalises it). See the module docstring.
#   139 overlap bins x 100 = 13900  ->  49.97%   (mates overlap, no readthrough)
#    38 short   bins x 110 =  4180  ->  15.03%   (readthrough 1..38: PE target)
#     1 saturating bin x 9735 =  9735  ->  35.00%
INSERT_WEIGHTS = (
    # (range_lo, range_hi, weight, role)
    (READ_LEN, CEILING, 100, "overlap"),
    (SHORT_LO, SHORT_HI, 110, "short"),
    (SATURATING, SATURATING, 9735, "saturated"),
)

# 5' leading G-run: mass at 0 AND at >= 1, so some reads carry a head run and
# some do not. 34% of mates carry one.
#
# The LENGTHS are chosen deliberately and are not cosmetic: the trim scorer
# compares the tool's 5' trim against this GT column, so a run is a usable
# reference only if the tool's own rule can see it. The polyX scan needs
# matches+1 >= min_run (12), i.e. a run of >= 12 bases; `--head-dropout N` (the
# published baseline is 0, hd4 trims 1..=4 exactly) needs 1..=N. So the run
# lengths below span both regimes: 1-2 bp (visible only to head-dropout, the
# hd4 arm) and 12-17 bp (visible to the plain scan).
HEAD = {"0": 1000, "1": 170, "2": 170, "12": 20, "13": 20,
        "14": 20, "15": 20, "16": 10, "17": 10}

# 3' polyG tail: mass at 0 AND at >= 1. The tail histogram is the *total*
# measured 3' G-run; fastsim's boundary rule forces the base before the run
# non-G, so the injected run is exactly what the GT records.
#
# 72% of mates carry no tail; the rest carry runs of 4..17 bases, spanning
# min_run (12) so the polyX scan has both sub-threshold and supra-threshold
# cases to be scored against.
_TAIL_NONZERO = {4: 30, 5: 35, 6: 60, 7: 55, 8: 45, 9: 30, 10: 20,
                 11: 12, 12: 10, 13: 8, 14: 6, 15: 4, 16: 3, 17: 2}
TAIL = {"0": 720, **{str(k): v for k, v in _TAIL_NONZERO.items()}}

# The joint R1 x R2 tail grid: identical marginals, correlated on the diagonal
# (real NovaSeq tails are correlated between mates). Built from TAIL so the
# joint's marginals are exactly the TAIL histogram.
JOINT: dict[str, int] = {f"{k},{k}": TAIL[k] for k in TAIL}

# Adapter: the real Illumina TruSeq R1 sequence, mode readthrough.
ADAPTER_SEQ = "AGATCGGAAGAGCACACGTCTGAACTCCAGTCA"


def build_insert_hist() -> dict[str, int]:
    """Sparse `{length: count}` histogram with an explicit 0 bin."""
    hist: dict[str, int] = {"0": 0}
    for lo, hi, weight, _role in INSERT_WEIGHTS:
        for i in range(lo, hi + 1):
            hist[str(i)] = weight
    return hist


def profile() -> dict:
    pos_q = {"R1": [37.0] * READ_LEN, "R2": [37.0] * READ_LEN}
    meanq = {"R1": {"37": 100}, "R2": {"37": 100}}
    return {
        "_comment": (
            "Cell B -- synthetic PE-overlap value-test cohort (see README.md). "
            "Carries BOTH G-runs and real TruSeq adapter readthrough, so the "
            "trim scorer's exact/overtrim reference is meaningful and the "
            "--pe-overlap mode has a boundary to find."
        ),
        "read_len": READ_LEN,
        "gc": 0.5,
        "geometry": "tail3p_both",
        "head": {"R1": dict(HEAD), "R2": dict(HEAD)},
        "tail": {"R1": dict(TAIL), "R2": dict(TAIL)},
        "joint_tail": dict(JOINT),
        "tail_q_collapse": {"R1": 3.0, "R2": 3.0},
        "pos_q": pos_q,
        "read_meanq": meanq,
        "full_length_rate": 0.0,
        "full_length_q": {"R1": 20, "R2": 20},
        "adapter": {"seq": ADAPTER_SEQ, "mode": "readthrough"},
        "insert": build_insert_hist(),
        "dup_rate": 0.0,
    }


def main() -> None:
    out = os.path.join(HERE, "cellB-profile.json")
    with open(out, "w") as fh:
        json.dump(profile(), fh, indent=1, sort_keys=False)
        fh.write("\n")
    # a legible summary on stdout, so the numbers are checkable without opening
    # the JSON: the mass split, and the run-length histograms' key bins.
    hist = build_insert_hist()
    tot = sum(hist.values())
    print(f"wrote {out}")
    for lo, hi, _w, role in INSERT_WEIGHTS:
        mass = sum(v for k, v in hist.items() if lo <= int(k) <= hi)
        print(f"  insert {role:10} [{lo}..{hi}]  {100 * mass / tot:5.2f}%")
    print(f"  total insert weight {tot}")
    print(f"head bins: {HEAD}")
    print(f"tail bins: {TAIL}")
    print(f"adapter: {ADAPTER_SEQ} (mode readthrough)")


if __name__ == "__main__":
    main()
